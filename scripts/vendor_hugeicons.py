"""Regenerate newsprism/static/icons/hugeicons-sprite.svg from Hugeicons free icons.

Source: @hugeicons/core-free-icons (MIT, hugeicons.com), pinned to PINNED_VERSION.
Requires network access. Run: .venv/bin/python scripts/vendor_hugeicons.py
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

# Slug -> Hugeicons module lives once, in the runtime module, so the vendoring
# script, the renderer and the report template can never drift apart.
from newsprism.runtime.icons import ICON_SLUGS  # noqa: E402  (path set above)

PINNED_VERSION = "4.3.2"
_CDN = "https://unpkg.com/@hugeicons/core-free-icons@{v}/dist/esm/{module}.js"

# Alternates measured for the same slot, kept for future swaps:
#   category-business: ChartUpIcon (1852 B)   category-science-health: Telescope01Icon (1272 B)
#   ui-theme-light:    Sun01Icon (1979 B)     ui-certified: CheckmarkBadge01Icon (1257 B)
#   topic-war:         SwordsIcon (1892 B)    category-world: EarthIcon (752 B)

_OUT = (
    REPO_ROOT
    / "newsprism" / "static" / "icons" / "hugeicons-sprite.svg"
)

_HEADER = (
    '<!-- Hugeicons free (stroke-rounded) v{v}, {n} icons.\n'
    "     Source: @hugeicons/core-free-icons, MIT licence, https://hugeicons.com\n"
    "     Generated by scripts/vendor_hugeicons.py — do not edit by hand. -->\n"
)


def _kebab(key: str) -> str:
    return re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", key).lower()


def _module_nodes(module: str, version: str) -> list:
    """Fetch one icon module and parse its JS array literal into JSON nodes."""
    url = _CDN.format(v=version, module=module)
    raw = urllib.request.urlopen(url, timeout=30).read().decode("utf-8")
    match = re.search(r"= (\[.*?\]);\n", raw, re.S)
    if not match:
        raise SystemExit(f"unexpected module shape: {url}")
    literal = match.group(1)
    # JS object literal -> JSON: quote bare keys, normalise quotes.
    literal = re.sub(r"([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', literal)
    literal = literal.replace("'", '"')
    return json.loads(literal)


def _nodes_to_svg(nodes: list) -> str:
    # Keep stroke="currentColor" on every node. SVG defaults stroke to none, so
    # dropping it (relying on the svg.icon CSS rule instead) renders every icon
    # invisible — verified by rendering the sprite in a browser. Costs 1,650 B raw
    # and only 42 B gzipped, and makes each symbol self-sufficient.
    parts: list[str] = []
    for tag, props in nodes:
        attrs = [
            f'{_kebab(k)}="{v}"'
            for k, v in props.items()
            if k != "key"
        ]
        parts.append(f"<{tag} " + " ".join(attrs) + "/>")
    return "".join(parts)


def build(version: str = PINNED_VERSION) -> str:
    cache: dict[str, str] = {}
    symbols: list[str] = []
    for slug, module in ICON_SLUGS.items():
        if module not in cache:
            cache[module] = _nodes_to_svg(_module_nodes(module, version))
        symbols.append(
            f'<symbol id="hi-{slug}" viewBox="0 0 24 24" fill="none">'
            f"{cache[module]}</symbol>"
        )
    header = _HEADER.format(v=version, n=len(ICON_SLUGS))
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">'
        + header
        + "".join(symbols)
        + "</svg>"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default=PINNED_VERSION)
    parser.add_argument("--check", action="store_true", help="verify the file is current")
    args = parser.parse_args()

    sprite = build(args.version)
    if args.check:
        current = _OUT.read_text(encoding="utf-8") if _OUT.exists() else ""
        if current != sprite:
            print("hugeicons-sprite.svg is stale; run without --check", file=sys.stderr)
            return 1
        print(f"up to date ({len(sprite)} bytes)")
        return 0

    _OUT.parent.mkdir(parents=True, exist_ok=True)
    _OUT.write_text(sprite, encoding="utf-8")
    _OUT.chmod(0o644)
    print(f"wrote {_OUT} ({len(sprite)} bytes, {len(ICON_SLUGS)} slugs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
